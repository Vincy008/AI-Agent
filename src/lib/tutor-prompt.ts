/**
 * 组装最终的系统消息内容
 */
export function buildSystemPrompt(
  module: keyof typeof MODULE_PROMPT | 'chat' = 'chat',
  extra?: string,
): string {
  const sub = MODULE_PROMPT[module] ?? MODULE_PROMPT.chat;
  return [TUTOR_SYSTEM_PROMPT, sub, extra].filter(Boolean).join('\n\n');
}
